-- Triplooper / Ganesh Residence — initial Postgres schema
-- Derived from application code usage (the legacy database.sql is stale MySQL).
-- Multi-tenant hotel + restaurant CRM. Tenant scoping via tenant_id -> tenants.id.
--
-- NOTE: Owner/user IDs are TEXT (Clerk string IDs mixed with Supabase uuids).
-- NOTE: reservations.id is TEXT (human IDs like RES-001); child FKs use text.
-- NOTE: The app also calls 9 Postgres RPC functions whose bodies do not exist in
--       the codebase (create_public_booking, check_room_availability, apply_coupon,
--       get_tenant_site, get_room_detail, get_guest_session, create_tenant,
--       create_staff_user, create_table_reservation, create_table_reservation).
--       Those are intentionally NOT defined here — see migration 20260629000001.

create extension if not exists "pgcrypto";

-- ============================================================
-- Core multi-tenancy
-- ============================================================

create table if not exists businesses (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  owner_id text not null,
  contact_email text,
  max_properties int not null default 1,
  max_rooms_per_property int not null default 50,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists tenants (
  id uuid primary key default gen_random_uuid(),
  business_name text not null,
  business_type text not null default 'hotel',           -- hotel | restaurant | combined
  subdomain text unique not null,
  template text not null default 'luxury',
  plan text not null default 'starter',                  -- starter | growth | enterprise
  custom_email text,
  logo_url text,
  is_active boolean not null default true,
  feature_toggles jsonb not null default '{}'::jsonb,
  business_id uuid references businesses(id) on delete set null,
  managed_by_business boolean not null default false,
  owner_id text not null,
  hero_image_url text,
  sections_visible jsonb,
  whatsapp_enabled boolean not null default false,
  evolution_api_url text,
  evolution_instance_name text,
  evolution_api_key text,
  google_review_url text,
  whatsapp_templates jsonb,
  created_at timestamptz not null default now()
);

create table if not exists user_properties (
  id uuid primary key default gen_random_uuid(),
  user_id text not null,
  tenant_id uuid not null references tenants(id) on delete cascade,
  role text not null default 'owner',
  is_owner boolean not null default false,
  unique (user_id, tenant_id)
);

create table if not exists business_invites (
  id uuid primary key default gen_random_uuid(),
  email text not null,
  business_name text not null,
  max_properties int not null default 1,
  max_rooms_per_property int not null default 50,
  invited_by text not null,
  token text unique not null default gen_random_uuid()::text,
  status text not null default 'pending',                -- pending | accepted
  created_at timestamptz not null default now()
);

create table if not exists staff (
  id uuid primary key,                                   -- = Supabase Auth user id
  tenant_id uuid not null references tenants(id) on delete cascade,
  name text not null,
  email text not null,
  phone text,
  role text not null,                                    -- stored UPPERCASE
  status text not null default 'ACTIVE',                 -- ACTIVE | ON_LEAVE | INACTIVE
  maintenance_notes text,
  created_at timestamptz not null default now()
);

-- ============================================================
-- Hotel
-- ============================================================

create table if not exists rooms (
  id bigint generated by default as identity primary key,
  tenant_id uuid not null references tenants(id) on delete cascade,
  room_number text,
  name text,
  type text,
  description text,
  price_per_night numeric(10,2) not null default 0,
  max_occupancy int not null default 2,
  amenities text[] not null default '{}',
  images text[] not null default '{}',
  status text not null default 'Available',              -- Available | Occupied | Maintenance
  cleaning_status text not null default 'Clean',         -- Clean | Dirty
  is_available boolean not null default true,
  show_on_website boolean not null default true,
  maintenance_notes text,
  created_at timestamptz not null default now()
);

create table if not exists reservations (
  id text primary key,                                   -- human ID e.g. RES-001
  tenant_id uuid not null references tenants(id) on delete cascade,
  guest_name text not null,
  guest_email text,
  guest_phone text,
  guest_location text,
  room_type text,
  room_id bigint references rooms(id) on delete set null,
  check_in date,
  check_out date,
  source text not null default 'DIRECT',
  status text not null default 'PENDING',
  payment_status text not null default 'PENDING',
  payment_method text,
  amount numeric(10,2) not null default 0,
  gst_amount numeric(10,2) not null default 0,
  payment_date timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists guest_tokens (
  id uuid primary key default gen_random_uuid(),
  reservation_id text not null references reservations(id) on delete cascade,
  token text unique not null default gen_random_uuid()::text,
  created_at timestamptz not null default now()
);

create table if not exists service_requests (
  id bigint generated by default as identity primary key,
  tenant_id uuid not null references tenants(id) on delete cascade,
  reservation_id text references reservations(id) on delete set null,
  room_id bigint references rooms(id) on delete set null,
  request_type text,
  description text,
  priority text not null default 'normal',
  status text not null default 'pending',                -- pending | completed | cancelled
  assigned_to text,
  created_at timestamptz not null default now(),
  completed_at timestamptz
);

create table if not exists guest_messages (
  id bigint generated by default as identity primary key,
  tenant_id uuid not null references tenants(id) on delete cascade,
  reservation_id text references reservations(id) on delete cascade,
  sender_type text not null,                             -- guest | staff
  sender_name text,
  message text not null,
  created_at timestamptz not null default now()
);

create table if not exists page_content (
  id bigint generated by default as identity primary key,
  tenant_id uuid not null references tenants(id) on delete cascade,
  section text not null,
  block_key text not null,
  content_text text,
  image_url text,
  is_active boolean not null default true,
  order_index int not null default 0,
  unique (tenant_id, section, block_key)
);

